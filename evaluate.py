def write_answer(output, answer):
    output.append("**Фактический ответ**")
    output.extend(["> " + line for line in answer.text.splitlines()])
    output.append("")
    for title, url in answer.sources:
        output.append(f"- [{title}]({url})")
    output.append("")


def main():
    bot = Assistant()
    report = [
        "# Результаты тестирования",
        "",
        f"Корпус: первый курс ИВТ МИЭМ, {YEAR}. Ответы получены вызовом той же функции, что использует CLI.",
        "В рабочих сценариях проверяются ключевые факты и ссылки; в сценариях ограничений — ожидаемое наблюдаемое поведение.",
        "Набор демонстрационный: из него нельзя выводить общую точность на новых вопросах.",
        "",
        "Для повтора: `python evaluate.py`.",
    ]
    positive_passed = 0
    reproduced = 0
    report.extend(["", "## 20 рабочих сценариев", ""])
    for number, (question, facts, source_keys) in enumerate(WORKING, start=1):
        answer = bot.answer(question)
        urls = [url for _, url in answer.sources]
        passed = answer.status == "answer" and all(fact.casefold() in answer.text.casefold() for fact in facts)
        passed = passed and all(any(key.replace("#", ".html#") in url for url in urls) for key in source_keys)
        positive_passed += int(passed)
        report.append(f"### {number}. {question}")
        report.append(f"**Ожидалось** {'; '.join(facts)}. **Результат** {'пройден' if passed else 'сбой'}.")
        write_answer(report, answer)
    report.extend(["## 10 сценариев с ограничениями", ""])
    for number, (question, status, snippet, reason) in enumerate(LIMITS, start=21):
        answer = bot.answer(question)
        observed = answer.status == status and snippet in answer.text
        if status == "answer":
            observed = observed and not any("#library" in url for _, url in answer.sources)
        reproduced += int(observed)
        report.append(f"### {number}. {question}")
        report.append(f"**Ограничение** {reason}")
        report.append(f"**Результат** {'воспроизведено' if observed else 'изменилось поведение'}.")
        write_answer(report, answer)
    report[2:2] = [f"**Итог** Рабочие сценарии — {positive_passed}/20. Ограничения воспроизведены — {reproduced}/10.", ""]
    print("\n".join(report).rstrip())
    if positive_passed != 20 or reproduced != 10:
        sys.exit(1)


if __name__ == "__main__":
    main()
